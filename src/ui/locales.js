/** Language codes stored in preferences, and the names players see in the picker. */
export const LANGUAGE_NAMES = Object.freeze({
    ko: '한국어', en: 'English', zh: '简体中文', ja: '日本語', 'zh-TW': '繁體中文',
    es: 'Español (España)', 'pt-BR': 'Português (Brasil)', ru: 'Русский', de: 'Deutsch', fr: 'Français',
});

const loaders = {
    ja: () => import('./locales/ja.js'),
    'zh-TW': () => import('./locales/zh-TW.js'),
    es: () => import('./locales/es.js'),
    'pt-BR': () => import('./locales/pt-BR.js'),
    ru: () => import('./locales/ru.js'),
    de: () => import('./locales/de.js'),
    fr: () => import('./locales/fr.js'),
};
const catalogs = new Map();
export const catalogFor = code => catalogs.get(code);
export const needsCatalog = code => Object.hasOwn(loaders, code) && !catalogs.has(code);
export async function loadCatalog(code) {
    const { default: catalog } = await loaders[code]();
    catalogs.set(code, catalog);
}

/** Old saves retain the original Korean and English names. Both identify the
 * source, including different game terms that happen to have the same English name. */
export function dataText(value, code) {
    if (value == null || typeof value === 'string') return value ?? '';
    if (code === 'ko' || code === 'en') return value[code] ?? value.ko ?? '';
    if (value[code] != null && value[code] !== '') return value[code];
    const en = value.en ?? '';
    const ko = value.ko ?? '';
    const catalog = catalogs.get(code);
    if (!catalog) return en || ko;
    const lookup = (k, e) => catalog.data[k + '\t' + e];
    const exact = lookup(ko, en);
    if (exact !== undefined) return exact;

    // Stat lines put the value after the Korean label and before the English label.
    const stat = /^([+−-]?[\d.,]+(?:~[+−-]?[\d.,]+)?%?) (.+)$/u.exec(en);
    if (stat && ko.endsWith(' ' + stat[1])) {
        const label = lookup(ko.slice(0, -stat[1].length - 1), stat[2]);
        if (label) return code === 'ja' ? label + ' ' + stat[1] : stat[1] + ' ' + label;
    }
    // Only multi-stage areas have a Roman numeral appended to the saved name.
    const cell = / ([IVXL]+)$/.exec(en);
    if (cell && ko.endsWith(cell[0])) {
        const area = lookup(ko.slice(0, -cell[0].length), en.slice(0, -cell[0].length));
        if (area) return area + cell[0];
    }
    // Equipment and elite names are generated by game_logic/naming.js. Translate
    // their individual words so equipment obtained in older versions works too.
    const cut = ko.indexOf('의 ');
    if (cut !== -1) {
        const words = en.split(' ');
        const first = catalog.affixes[words[0]];
        const second = words[1] === 'and' && catalog.affixes[words[2]];
        if (first) {
            const base = lookup(ko.slice(cut + 2), words.slice(second ? 3 : 1).join(' '));
            if (base) {
                if (code === 'ja') return (second ? first + '・' + second : first) + 'の' + base;
                if (code === 'zh-TW') return (second ? first + '與' + second : first) + '之' + base;
                return base + ' · ' + (second ? first + ' / ' + second : first);
            }
        }
    }
    return en || ko;
}
